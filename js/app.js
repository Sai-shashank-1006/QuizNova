  function startLoop() {
    cancelAnimationFrame(S.raf);
    let last = now();
    const step = () => {
      const g = S.game;
      if (!g || g.phase === 'done') return;
      const t = now();
      // Freeze the clock while a dialog (e.g. "Quit game?") is open — except online, where others keep playing.
      if ($('dialog[open]') && g.kind !== 'online') {
        const dt = t - last;
        for (const key of ['phaseEnds', 'deadline', 'qStart', 'openedAt']) if (g[key] != null) g[key] += dt;
      } else if (g.kind === 'solo') soloFrame(t);
      else if (g.kind === 'online') onlineFrame(t);
      else battleFrame(t);
      last = t;
      if (S.game === g && g.phase !== 'done') { updateTop(); S.raf = requestAnimationFrame(step); }
    };
    S.raf = requestAnimationFrame(step);
  }
  const stopLoop = () => cancelAnimationFrame(S.raf);
  function stopGame() {
    stopLoop();
    const g = S.game;
    if (g && g.feed && g.feed.abort && !g.feed.done) g.feed.abort.abort();
    S.game = null;
    updateTop();
  }

