  // A wrong AI answer reported from the results: it stops counting (score, accuracy, stats) and won't be asked again
  // (it's already in the AI history, which is sent as "don't repeat these").
  function reportQuestion(i) {
    const res = S.lastResult;
    if (!res || res.kind !== 'solo') return;
    const q = res.questions[i], a = res.answers[i];
    if (!q || !a || !q.ai || a.voided) return;
    const p = res.rec.players[0], from = p.score;
    a.voided = true;
    p.score = Math.max(0, p.score - a.points);
    a.points = 0;
    a.correct = false;
    const kept = res.answers.filter(x => !x.voided), right = kept.filter(x => x.correct);
    Object.assign(p, {
      correct: right.length, answered: kept.length,
      avgMs: avg(right.map(x => x.ms)), fastest: right.length ? Math.min(...right.map(x => x.ms)) : null,
      speed: avg(right.map(x => 1 - x.ms / x.limit)) || 0, totalMs: Math.round(kept.reduce((t, x) => t + x.ms, 0)),
    });
    const all = store.get(K.games, []);
    const k = Array.isArray(all) ? all.findIndex(x => x && x.gid === res.rec.gid) : -1;
    if (k >= 0) { all[k] = res.rec; store.set(K.games, all); }
    const y = window.scrollY;
    renderSoloResults({ from });
    window.scrollTo(0, y);
    toast('Thanks — that question no longer counts, and it won’t be asked again.', 'flag', 'good');
  }

