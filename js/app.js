  function finishSolo() {
    const g = S.game;
    g.phase = 'done';
    stopLoop();
    if (g.feed.abort && !g.feed.done) g.feed.abort.abort();
    const right = g.answers.filter(a => a.correct);
    const rec = {
      gid: uid(), mode: g.challenge ? 'challenge' : 'solo', subject: g.subject, topic: g.topic || undefined, source: g.source,
      n: g.answers.length, speed: g.speed, seed: g.seed, at: now(),
      players: [{
        id: S.user.id, score: g.score, correct: right.length, answered: g.answers.length,
        avgMs: avg(right.map(a => a.ms)), fastest: right.length ? Math.min(...right.map(a => a.ms)) : null,
        speed: avg(right.map(a => 1 - a.ms / a.limit)) || 0, streak: g.bestStreak,
        totalMs: Math.round(g.answers.reduce((t, a) => t + a.ms, 0)),
      }],
      challenge: g.challenge ? { by: g.challenge.by, sc: g.challenge.sc, c: g.challenge.c, t: g.challenge.t } : null,
    };
    const prevBest = bestFor(S.user.id, g.subject);
    saveGame(rec);
    S.lastResult = { kind: 'solo', rec, answers: g.answers, questions: g.questions.slice(0, g.answers.length), prevBest, difficulty: g.difficulty };
    renderSoloResults();
    showView('results');
  }

  // Challenge winner: higher score, then more correct answers, then less total time.
