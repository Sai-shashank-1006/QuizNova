  async function handleAuthSubmit(form) {
    const ctx = form.dataset.ctx, mode = form.dataset.mode;
    clearErrors(form);
    const id = form.elements.id.value.trim();
    const pass = form.elements.password.value;
    const confirm = form.elements.confirm ? form.elements.confirm.value : pass;
    let ok = true;
    if (!ID_RE.test(id)) ok = fieldError(form, 'id', id ? 'Use 3–16 letters, numbers, _ or -.' : 'Enter a player ID.');
    if (pass.length < 4) ok = fieldError(form, 'password', 'Use at least 4 characters.');
    else if (mode === 'create' && pass !== confirm) ok = fieldError(form, 'confirm', 'The passwords don’t match.');
    if (!ok) { form.querySelector('.invalid')?.focus(); return; }

    const btn = form.querySelector('[type="submit"]');
    btn.disabled = true;
    try {
      let acc;
      if (mode === 'create') {
        acc = account(id) ? null : await createAccount(id, pass);
        if (!acc) { fieldError(form, 'id', 'That ID already exists on this device — log in instead.'); return; }
      } else {
        acc = account(id);
        if (!acc) { fieldError(form, 'id', 'No player with that ID on this device yet — create it first.'); return; }
        if (!(await checkPassword(acc, pass))) { fieldError(form, 'password', 'Wrong password.'); form.elements.password.select(); return; }
      }
      if (ctx === 'player') {
        if (S.roster.some(r => idKey(r.id) === idKey(acc.id))) { fieldError(form, 'id', 'That player is already in this battle.'); return; }
        S.roster.push({ id: acc.id });
        $('#dlg-player').close();
        renderRoster();
        toast(`${acc.id} joined the battle`, 'users', 'good');
      } else {
        login(acc, mode === 'create');
      }
    } finally {
      btn.disabled = false;
    }
  }

