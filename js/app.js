  function finishBattle() {
    const g = S.game;
    g.phase = 'done';
    stopLoop();
    if (g.feed.abort && !g.feed.done) g.feed.abort.abort();
    const ranked = g.players.slice().sort((a, b) => b.score - a.score || b.correct - a.correct);
    const top = ranked[0];
    const winners = ranked.filter(p => p.score === top.score && p.correct === top.correct);
    const rec = {
      gid: uid(), mode: 'battle', subject: g.subject, topic: g.topic || undefined, source: g.source,
      n: Math.min(g.n, g.i + 1), seed: g.seed, at: now(),
      players: g.players.map(p => ({
        id: p.id, score: p.score, correct: p.correct, wrong: p.wrong, answered: p.correct + p.wrong,
        avgMs: avg(p.reactions), speed: avg(p.reactions.map(r => Math.max(0, 1 - r / 8000))) || 0, streak: 0,
      })),
      winners: winners.map(p => p.id),
    };
    saveGame(rec);
    S.lastResult = { kind: 'battle', rec, ranked, winners, setup: g.setup };
    renderBattleResults();
    showView('results');
    confetti(120);
    SFX.win();
  }

