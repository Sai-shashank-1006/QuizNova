  // An AI question whose own parts disagree (its "correct" text, its explanation and the answer it marked)
  // is probably wrong, so it is dropped. Costs nothing: no extra AI call.
  const UNSURE = 'unsure';
  const escRe = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const mentions = (text, phrase) => phrase.length >= 2 && new RegExp(`(^|[^a-z0-9])${escRe(phrase)}($|[^a-z0-9])`).test(text);
  const numbersIn = text => (String(text).replace(/[\u2212\u2013]/g, '-').match(/-?\d+(?:\.\d+)?(?:\/\d+)?/g) || []).map(v => (M ? M.parseNumber(v) : +v));
  function agreesWithItself(r, opts, idx, maths) {
    const said = typeof r.correct === 'string' ? normAnswer(r.correct) : '';
    const norm = opts.map(normAnswer);
    if (said) {
      const exact = norm.indexOf(said);
      if (exact >= 0 && exact !== idx) return false; // names a different option than the one marked
    }
    const explain = typeof r.explain === 'string' ? r.explain : '';
    if (!explain) return true;
    if (maths) {
      const value = M ? M.parseNumber(opts[idx]) : NaN;
      const nums = numbersIn(explain);
      return !Number.isFinite(value) || !nums.length || nums.some(v => Math.abs(v - value) < 1e-6);
    }
    const ex = normAnswer(explain);
    const named = norm.map((o, k) => (mentions(ex, o) ? k : -1)).filter(k => k >= 0);
    return !named.length || named.includes(idx); // the explanation backs a different option
  }

  // Turns one AI question into the game's format, or null if it isn't usable (UNSURE if it contradicts itself).
  function normalizeAI(r, mcqOnly, maths = false) {
    if (!r || typeof r.question !== 'string') return null;
    const q = r.question.trim().slice(0, 300);
    if (q.length < 8) return null;
    const base = {
      q, ai: true,
      explain: typeof r.explain === 'string' ? r.explain.trim().slice(0, 240) : '',
      difficulty: DIFF_MULT[r.difficulty] ? r.difficulty : 'medium',
    };
    if (maths) base.tx = MATHS_TX[base.difficulty];
    if (r.type === 'truefalse') {
      if (r.answer !== 0 && r.answer !== 1) return null;
      const said = typeof r.correct === 'string' ? normAnswer(r.correct) : '';
      if ((said === 'true' && r.answer !== 0) || (said === 'false' && r.answer !== 1)) return UNSURE;
      return { ...base, type: 'mcq', tf: true, options: ['True', 'False'], answer: r.answer };
    }
    if (r.type === 'written') {
      if (mcqOnly) return null;
      const accept = (Array.isArray(r.accept) ? r.accept : []).filter(x => typeof x === 'string' && x.trim()).map(x => x.trim().slice(0, 60)).slice(0, 8);
      const value = maths && M ? M.parseNumber(accept[0]) : NaN;
      if (Number.isFinite(value) && r.explain && numbersIn(r.explain).length && !numbersIn(r.explain).some(v => Math.abs(v - value) < 1e-6)) return UNSURE;
      return accept.length ? { ...base, type: 'written', accept, answerText: accept[0], num: Number.isFinite(value) ? value : undefined } : null;
    }
    const opts = (Array.isArray(r.options) ? r.options : []).filter(x => typeof x === 'string' && x.trim()).map(x => x.trim().slice(0, 120));
    if (opts.length !== 4 || new Set(opts.map(o => o.toLowerCase())).size !== 4) return null;
    if (!Number.isInteger(r.answer) || r.answer < 0 || r.answer > 3) return null;
    if (!agreesWithItself(r, opts, r.answer, maths)) return UNSURE;
    const perm = shuffle([0, 1, 2, 3]);
    return { ...base, type: 'mcq', options: perm.map(k => opts[k]), answer: perm.indexOf(r.answer) };
  }

